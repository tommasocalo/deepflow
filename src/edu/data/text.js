export function dtx(key, params = {}) {
    const locale = getLocale();
    const raw = DATA_TEXT[locale]?.[key] ?? DATA_TEXT.en[key];
    if (typeof raw !== 'string') return key;
    return raw.replace(/\{([A-Za-z_][\w]*)\}/g, (match, name) => (params[name] === undefined || params[name] === null ? match : String(params[name])));
}
