import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';

const directory = process.env.SCREENSHOT_DIR ?? 'screenshots/attention';
await mkdir(directory, { recursive: true });
const browser = await chromium.launch();
try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
    page.setDefaultTimeout(8000);
    const errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    await page.goto(process.env.URL ?? 'http://127.0.0.1:4183/');
    await page.getByRole('button', { name: 'Examples', exact: true }).click();
    await page.getByRole('group', { name: 'Example architectures' }).getByRole('button', { name: /^Multi-head attention/ }).click();
    const ribbon = page.getByRole('region', { name: /Architecture ribbon/ });
    const settle = () => page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    const fit = async () => { await ribbon.getByRole('button', { name: 'Fit active graph', exact: true }).click(); await page.waitForTimeout(300); };
    await page.locator('.df-parallel-instance').first().waitFor();
    await fit();
    assert.equal(await page.locator('.df-parallel-instance').count(), 12);
    assert.equal(await page.locator('.df-parallel .react-flow__handle.target').count(), 3);
    assert.match(await page.locator('.df-parallel .df-port-shape--output').innerText(), /12 tensors \[B × 128 × 64\]/);
    await page.screenshot({ path: `${directory}/01-attention-overview.png` });
    await page.getByRole('button', { name: 'Open Attention heads instance 8', exact: true }).click();
    await page.getByRole('spinbutton', { name: 'Inspected instance number' }).waitFor();
    await fit();
    assert.equal(await page.getByRole('spinbutton', { name: 'Inspected instance number' }).inputValue(), '8');
    assert.equal(await page.locator('[data-handleid="a"]').count(), 2);
    assert.equal(await page.locator('[data-handleid="b"]').count(), 2);
    assert.match(await page.locator('.df-port-shape').allTextContents().then((texts) => texts.join(' ')), /B × 128 × 64/);
    assert.equal(await page.evaluate(() => Object.values(window.__deepflow.architectureStore.getState().inspectedIterations).at(-1)), 7, 'Human instance 8 retains formula index 7');
    assert.equal(await page.getByText('index starts at 0', { exact: false }).count(), 0);
    await page.screenshot({ path: `${directory}/02-head-body.png` });
    await page.getByRole('button', { name: 'Next instance', exact: true }).click();
    assert.equal(await page.getByRole('spinbutton', { name: 'Inspected instance number' }).inputValue(), '9');
    await page.getByRole('tab', { name: 'Multi-head attention', exact: true }).click();
    await ribbon.getByRole('button', { name: 'Edit template parameters', exact: true }).click();
    await page.getByRole('textbox', { name: 'H default value', exact: true }).fill('8');
    await page.getByRole('button', { name: 'Close template parameters', exact: true }).click();
    await settle();
    assert.equal(await page.locator('.df-parallel-instance').count(), 8);
    assert.match(await page.locator('.df-parallel .df-port-shape--output').innerText(), /8 tensors \[B × 128 × 96\]/);
    await page.screenshot({ path: `${directory}/03-eight-heads.png` });
    await page.locator('.df-parallel-header strong').click();
    await page.getByRole('textbox', { name: 'count', exact: true }).waitFor();
    assert.equal(await page.getByRole('combobox', { name: 'Repeat mode', exact: true }).count(), 0, 'The inspector has no duplicate structure mode');
    assert.equal(await ribbon.getByRole('button', { name: 'Repeat selection in parallel', exact: true }).getAttribute('aria-pressed'), 'true');
    assert.equal(await page.getByRole('textbox', { name: 'count', exact: true }).inputValue(), '$H');
    assert.equal(await page.locator('.df-inspector [data-parameter="count"] label').innerText(), 'Instances');
    assert.equal(await page.getByRole('textbox', { name: 'iterationVariable', exact: true }).isVisible(), false, 'Formula index is an advanced setting');
    await page.screenshot({ path: `${directory}/04-parallel-settings.png` });
    await page.getByRole('button', { name: 'Close inspector', exact: true }).click();
    await page.locator('.react-flow__pane').click({ position: { x: 150, y: 180 } });
    await ribbon.getByRole('button', { name: 'Edit template parameters', exact: true }).click();
    await page.getByRole('textbox', { name: 'H default value', exact: true }).fill('5');
    await page.getByRole('button', { name: 'Close template parameters', exact: true }).click();
    await settle();
    assert.ok(await page.locator('.df-parallel--error').count(), 'An indivisible feature width produces a visible validation error');
    await page.screenshot({ path: `${directory}/05-invalid-head-count.png` });
    await ribbon.getByRole('button', { name: 'Edit template parameters', exact: true }).click();
    await page.getByRole('textbox', { name: 'H default value', exact: true }).fill('8');
    await page.getByRole('button', { name: 'Close template parameters', exact: true }).click();
    await page.locator('.df-parallel-header strong').click();
    await ribbon.getByRole('button', { name: 'Open to the side', exact: true }).click();
    const main = page.locator('[data-graph-pane="main"]');
    const side = page.locator('[data-graph-pane="side"]');
    assert.equal(await side.getByRole('spinbutton', { name: 'Inspected instance number' }).inputValue(), '8', 'Open to side preserves the source pane inspection context');
    await side.getByRole('spinbutton', { name: 'Inspected instance number' }).fill('8');
    await fit();
    await main.locator('.react-flow__pane').click({ position: { x: 100, y: 150 } });
    await ribbon.getByRole('button', { name: 'Edit template parameters', exact: true }).click();
    await page.getByRole('textbox', { name: 'H default value', exact: true }).fill('4');
    await page.getByRole('button', { name: 'Close template parameters', exact: true }).click();
    await settle();
    assert.equal(await main.locator('.df-parallel-instance').count(), 4);
    assert.equal(await side.getByRole('spinbutton', { name: 'Inspected instance number' }).inputValue(), '4', 'Reducing H clamps an open pane to a valid head index');
    assert.match(await side.locator('.df-port-shape').allTextContents().then((texts) => texts.join(' ')), /B × 128 × 192/, 'A second pane updates derived head dimensions');
    await fit();
    await page.screenshot({ path: `${directory}/06-attention-and-head.png` });
    assert.deepEqual(errors, []);
    console.log('Attention browser checks passed: explicit Q/K/V ports, head inspection, H parameter updates, inferred dimensions, compact settings, invalid H, two-pane shape/index updates.');
} finally {
    await browser.close();
}
