import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';

const directory = process.env.SCREENSHOT_DIR ?? '/tmp/deepflow-ribbon';
await mkdir(directory, { recursive: true });
const browser = await chromium.launch();
try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
    page.setDefaultTimeout(6000);
    const errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    await page.goto(process.env.URL ?? 'http://127.0.0.1:5173/');
    const ribbon = page.getByRole('region', { name: /Architecture ribbon/ });
    const main = page.locator('[data-graph-pane="main"]');
    const side = page.locator('[data-graph-pane="side"]');
    const settle = () => page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    const root = () => page.evaluate(() => window.__deepflow.architectureStore.getState().graph);
    const selected = () => page.evaluate(() => {
        const state = window.__deepflow.architectureStore.getState();
        return state.graph.nodes[state.selectedNodeIds[0]];
    });
    await ribbon.waitFor();
    await settle();
    assert.equal(await ribbon.count(), 1);
    assert.equal(await page.locator('.df-library').count(), 0, 'No library overlays the graph until requested');
    assert.equal(await ribbon.getByRole('button', { name: 'Repeat selection in parallel' }).isDisabled(), true);
    for (const width of [1440, 1024]) {
        await page.setViewportSize({ width, height: 900 });
        await settle();
        assert.equal(await ribbon.evaluate((element) => element.scrollWidth <= element.clientWidth), true, `${width}px ribbon fits without horizontal overflow`);
        assert.equal(await ribbon.getByRole('button', { name: 'Fit active graph' }).isVisible(), true);
        await page.screenshot({ path: `${directory}/ribbon-${width}.png` });
    }
    await page.setViewportSize({ width: 1440, height: 960 });
    await ribbon.getByRole('button', { name: 'Search all blocks' }).click();
    const library = page.getByRole('dialog', { name: 'Block library', exact: true });
    await library.getByRole('textbox', { name: 'Search blocks', exact: true }).fill('group norm');
    assert.equal(await library.locator('.df-library-tile').count(), 1);
    await page.screenshot({ path: `${directory}/library-search.png` });
    await library.getByRole('textbox', { name: 'Search blocks', exact: true }).press('Enter');
    assert.equal((await selected()).libraryKey, 'torch.nn.LayerNorm');
    assert.equal(await library.count(), 0);
    await ribbon.getByRole('button', { name: 'Group selection into component', exact: true }).click();
    await page.getByRole('textbox', { name: 'Component name', exact: true }).fill('Ribbon component');
    await page.getByRole('button', { name: 'Create component', exact: true }).click();
    assert.equal((await selected()).kind, 'supernode');
    await ribbon.getByRole('button', { name: 'Repeat selection in parallel', exact: true }).click();
    assert.equal((await selected()).kind, 'repeat');
    assert.equal((await selected()).mode, 'parallel');
    await ribbon.getByRole('button', { name: 'Repeat selection sequentially', exact: true }).click();
    assert.equal((await selected()).mode, 'sequential');
    await ribbon.getByRole('button', { name: 'Edit template parameters', exact: true }).click();
    const params = page.getByRole('dialog', { name: 'Ribbon component template parameters', exact: true });
    assert.ok(await params.getByRole('textbox', { name: 'Template name', exact: true }).isVisible());
    await params.getByRole('textbox', { name: 'New parameter', exact: true }).fill('width');
    await params.getByRole('button', { name: 'Add parameter', exact: true }).click();
    await params.getByRole('textbox', { name: 'width default value', exact: true }).fill('32');
    await page.screenshot({ path: `${directory}/template-parameters.png` });
    await params.getByRole('button', { name: 'Close template parameters', exact: true }).click();
    const component = await selected();
    await ribbon.getByRole('button', { name: 'Open to the side', exact: true }).click();
    await side.waitFor();
    await settle();
    assert.equal(await ribbon.count(), 1, 'Split panes share one ribbon');
    assert.equal(await ribbon.getAttribute('data-active-pane'), 'side');
    const templateGraph = () => page.evaluate((id) => window.__deepflow.templatesStore.getState().templates[id].graph, component.templateId);
    const originalRoot = await root();
    const beforeTemplate = await templateGraph();
    await ribbon.getByRole('button', { name: 'Add Linear', exact: true }).click();
    assert.equal(Object.keys((await templateGraph()).nodes).length, Object.keys(beforeTemplate.nodes).length + 1);
    assert.deepEqual(await root(), originalRoot, 'An insert in the focused template pane leaves the root graph untouched');
    await main.getByRole('tab', { name: 'main', exact: true }).click();
    const beforeMain = await root();
    await ribbon.getByRole('button', { name: 'Add Activation', exact: true }).click();
    assert.equal(Object.keys((await root()).nodes).length, Object.keys(beforeMain.nodes).length + 1);
    assert.equal(await ribbon.getAttribute('data-active-pane'), 'main');
    const beforeDrop = Object.keys((await templateGraph()).nodes).length;
    await ribbon.getByRole('button', { name: 'Add Convolution', exact: true }).dragTo(side.locator('.react-flow__pane'), { targetPosition: { x: 120, y: 180 } });
    await settle();
    assert.equal(Object.keys((await templateGraph()).nodes).length, beforeDrop + 1);
    assert.equal(await ribbon.getAttribute('data-active-pane'), 'side', 'A drop activates the destination pane');
    await page.keyboard.press('Control+k');
    assert.equal(await page.getByRole('textbox', { name: 'Search blocks', exact: true }).evaluate((element) => element === document.activeElement), true);
    await page.keyboard.press('Escape');
    assert.equal(await library.count(), 0);
    assert.equal(await ribbon.getByRole('button', { name: 'Search all blocks' }).evaluate((element) => element === document.activeElement), true, 'Escape returns focus to the ribbon trigger');
    await page.screenshot({ path: `${directory}/split-ribbon.png` });
    const mainViewport = await main.locator('.react-flow__viewport').getAttribute('style');
    await ribbon.getByRole('button', { name: 'Fit active graph', exact: true }).click();
    await settle();
    assert.equal(await main.locator('.react-flow__viewport').getAttribute('style'), mainViewport, 'Fit affects only the active graph');
    assert.deepEqual(errors, []);
    console.log(`Ribbon checks passed: 1440/1024 layout, search, grouping, sequential/parallel conversion, template parameters, active-pane insert/fit, drag to side, keyboard focus. Screenshots: ${directory}`);
} finally {
    await browser.close();
}
